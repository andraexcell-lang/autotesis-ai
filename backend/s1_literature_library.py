def _merge_topic_presets() -> None:
    """
    Menggabungkan definisi Bab II dan entri pustaka dari preset topik ke
    perpustakaan literatur utama. Kunci yang sudah ada TIDAK ditimpa agar
    perilaku sektor lama tetap utuh.
    """
    try:
        import s1_topic_presets as _tp
    except Exception:
        return

    for key, data in _tp.iter_bab2_definitions():
        k = " ".join((key or "").lower().split()).strip(" .,;:")
        if k and k not in S1_DEFINITIONS_BAB2:
            S1_DEFINITIONS_BAB2[k] = dict(data)

    existing = {str(e.get("cite", "")).strip() for e in S1_EXPANDED_BIBLIOGRAPHY}
    for entry in _tp.iter_bibliography():
        cite = str(entry.get("cite", "")).strip()
        if cite and cite in existing:
            continue
        if cite:
            existing.add(cite)
        S1_EXPANDED_BIBLIOGRAPHY.append(dict(entry))


_merge_topic_presets()
